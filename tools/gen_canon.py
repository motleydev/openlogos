#!/usr/bin/env python3
"""Generates crates/core/src/canon/data.rs, the canon and versification table of B078.

Structure only, no text: chapters per book and verses per chapter in the Paratext `eng`
(English, KJV-style) and `org` (original: Hebrew BHS/WLC numbering for the Old Testament)
schemes, and the `eng` -> `org` mapping rows, for the 66 books of the Protestant canon.

Source: S51 (specs/10-sources.md), the Copenhagen Alliance versification mappings derived
from the Paratext .vrs files: versification-mappings/standard-mappings/eng.json and org.json
of https://github.com/Copenhagen-Alliance/versification-specification at the commit passed as
--commit. That repository licenses its data CC BY-SA 4.0; the generated file carries the
attribution. Deuterocanonical books are in the same files and are skipped here until
`BookId` gains them (the hook: extend BOOKS below and the generated arrays grow with it).

Usage (no network; fetch the two files yourself, they are not committed):

    python3 tools/gen_canon.py --eng eng.json --org org.json --commit <sha> \
        > crates/core/src/canon/data.rs
"""
import argparse
import hashlib
import json
import re
import sys

# The 66 books in BookId order: (Paratext code, OSIS id).
BOOKS = [
    ("GEN", "Gen"), ("EXO", "Exod"), ("LEV", "Lev"), ("NUM", "Num"), ("DEU", "Deut"),
    ("JOS", "Josh"), ("JDG", "Judg"), ("RUT", "Ruth"), ("1SA", "1Sam"), ("2SA", "2Sam"),
    ("1KI", "1Kgs"), ("2KI", "2Kgs"), ("1CH", "1Chr"), ("2CH", "2Chr"), ("EZR", "Ezra"),
    ("NEH", "Neh"), ("EST", "Esth"), ("JOB", "Job"), ("PSA", "Ps"), ("PRO", "Prov"),
    ("ECC", "Eccl"), ("SNG", "Song"), ("ISA", "Isa"), ("JER", "Jer"), ("LAM", "Lam"),
    ("EZK", "Ezek"), ("DAN", "Dan"), ("HOS", "Hos"), ("JOL", "Joel"), ("AMO", "Amos"),
    ("OBA", "Obad"), ("JON", "Jonah"), ("MIC", "Mic"), ("NAM", "Nah"), ("HAB", "Hab"),
    ("ZEP", "Zeph"), ("HAG", "Hag"), ("ZEC", "Zech"), ("MAL", "Mal"),
    ("MAT", "Matt"), ("MRK", "Mark"), ("LUK", "Luke"), ("JHN", "John"), ("ACT", "Acts"),
    ("ROM", "Rom"), ("1CO", "1Cor"), ("2CO", "2Cor"), ("GAL", "Gal"), ("EPH", "Eph"),
    ("PHP", "Phil"), ("COL", "Col"), ("1TH", "1Thess"), ("2TH", "2Thess"), ("1TI", "1Tim"),
    ("2TI", "2Tim"), ("TIT", "Titus"), ("PHM", "Phlm"), ("HEB", "Heb"), ("JAS", "Jas"),
    ("1PE", "1Pet"), ("2PE", "2Pet"), ("1JN", "1John"), ("2JN", "2John"), ("3JN", "3John"),
    ("JUD", "Jude"), ("REV", "Rev"),
]
INDEX = {code: i for i, (code, _) in enumerate(BOOKS)}
SIDE = re.compile(r"^([1-4A-Z]{3}) (\d+):(\d+)(?:-(\d+))?$")


def side(text):
    m = SIDE.match(text)
    if not m:
        return None
    book, chapter, first, last = m.groups()
    return book, int(chapter), int(first), int(last or first)


def counts(data):
    out = []
    for code, _ in BOOKS:
        out.append([int(v) for v in data["maxVerses"][code]])
    return out


def rows(data):
    out = []
    for source, target in data["mappedVerses"].items():
        a, b = side(source), side(target)
        if a is None or b is None or a[0] not in INDEX:
            continue  # deuterocanon or sub-verse rows (Greek Esther): not in BookId yet
        if a[0] != b[0]:
            raise SystemExit(f"cross-book row {source} = {target}")
        if a[3] - a[2] != b[3] - b[2]:
            raise SystemExit(f"uneven row {source} = {target}")
        out.append((INDEX[a[0]], a[1], a[2], a[3], b[1], b[2]))
    return sorted(out)


def array(name, doc, table):
    lines = [f"/// {doc}", f"pub(super) const {name}: [&[u8]; 66] = ["]
    for (code, osis), verses in zip(BOOKS, table):
        lines.append(f"    // {osis}")
        lines.append("    &[" + ", ".join(str(v) for v in verses) + "],")
    lines.append("];")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--eng", required=True)
    p.add_argument("--org", required=True)
    p.add_argument("--commit", required=True)
    args = p.parse_args()
    eng_bytes = open(args.eng, "rb").read()
    org_bytes = open(args.org, "rb").read()
    eng, org = json.loads(eng_bytes), json.loads(org_bytes)
    if org["mappedVerses"] and any(side(k) and side(k)[0] in INDEX for k in org["mappedVerses"]):
        raise SystemExit("org.json maps a canonical book: org is the base and maps nothing")
    eng_rows = rows(eng)
    for r in eng_rows:
        if max(r) > 255:
            raise SystemExit(f"row does not fit u8: {r}")
    out = [
        "// GENERATED by tools/gen_canon.py: do not edit by hand. Structure only, no text.",
        "//",
        "// Source: S51 (specs/10-sources.md), Copenhagen Alliance Versification Working Group,",
        "// versification-mappings/standard-mappings/eng.json and org.json (derived from the",
        "// Paratext .vrs files), https://github.com/Copenhagen-Alliance/versification-specification",
        f"// at commit {args.commit}.",
        "// Data licence CC BY-SA 4.0; changes: reduced to the 66 books of the Protestant canon",
        "// and re-encoded as Rust arrays.",
        f"// sha256 eng.json {hashlib.sha256(eng_bytes).hexdigest()}",
        f"// sha256 org.json {hashlib.sha256(org_bytes).hexdigest()}",
        "",
        f'/// The S51 commit the table was generated from.',
        f'pub(super) const SOURCE_COMMIT: &str = "{args.commit}";',
        "",
        array("ENG", "Verses per chapter in `eng`, by `BookId::canonical_index` (verse 0, a Psalm title, not counted).", counts(eng)),
        "",
        array("ORG", "Verses per chapter in `org`, by `BookId::canonical_index`.", counts(org)),
        "",
        "/// `eng` -> `org` rows: (book index, eng chapter, eng first verse, eng last verse, org",
        "/// chapter, org first verse), each a run of consecutive verses; sorted. A verse no row",
        "/// covers has the same number in both schemes (the .vrs rule), if `org` has it.",
        "pub(super) const ENG_TO_ORG: &[(u8, u8, u8, u8, u8, u8)] = &[",
    ]
    for r in eng_rows:
        out.append(f"    ({r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]}), // {BOOKS[r[0]][1]}")
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
